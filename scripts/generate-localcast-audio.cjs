/* global __dirname */
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');

const sourcePath = path.join(__dirname, '../src/services/LocalCastAudio.ts');
const outputPath = path.join(__dirname, '../src/services/generated/LocalCastAudioSource.ts');

function browserSource(file, name) {
  const source = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
  const factory = source.statements.find(statement => ts.isFunctionDeclaration(statement) && statement.name?.text === name);
  if (!factory) throw new Error('LocalCast factory not found: ' + name);
  const browserFactory = ts.factory.updateFunctionDeclaration(factory, undefined, factory.asteriskToken, factory.name,
    factory.typeParameters, factory.parameters, factory.type, factory.body);
  const printed = ts.createPrinter().printNode(ts.EmitHint.Unspecified, browserFactory, source);
  return ts.transpileModule(printed, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.None } }).outputText.trim();
}
function generateLocalCastAudioSource() {
  const javascript = browserSource(sourcePath, 'createLocalCastAudio');
  return '// Generated by npm run generate:localcast. Edit LocalCastAudio.ts instead.\n'
    + `export const localCastAudioSource = ${JSON.stringify(javascript)};\n`;
}

const viewOutputPath = path.join(__dirname, '../src/services/generated/LocalCastViewSource.ts');
function generateLocalCastViewSource() {
  const file = path.join(__dirname, '../src/services/LocalCastView.ts');
  return '// Generated by npm run generate:localcast. Edit LocalCastView.ts instead.\n'
    + ['Queue', 'Lyrics'].map(name => `export const localCast${name}Source = ${JSON.stringify(browserSource(file, `createLocalCast${name}View`))};\n`).join('');
}

const replayGainOutputPath = path.join(__dirname, '../src/services/generated/LocalCastReplayGainSource.ts');
function generateLocalCastReplayGainSource() {
  const file = path.join(__dirname, '../src/services/LocalCastReplayGain.ts');
  return '// Generated by npm run generate:localcast. Edit LocalCastReplayGain.ts instead.\n'
    + `export const castReplayGainMathSource = ${JSON.stringify(browserSource(file, 'calculateCastReplayGain'))};\n`
    + `export const castReplayGainSource = ${JSON.stringify(browserSource(file, 'createLocalCastReplayGain'))};\n`;
}

if (require.main === module) {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, generateLocalCastAudioSource());
  fs.writeFileSync(viewOutputPath, generateLocalCastViewSource());
  fs.writeFileSync(replayGainOutputPath, generateLocalCastReplayGainSource());
}

module.exports = { generateLocalCastAudioSource, outputPath, generateLocalCastViewSource, viewOutputPath, generateLocalCastReplayGainSource, replayGainOutputPath };
